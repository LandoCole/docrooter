"""MkDocs hooks for the docrooter site (``hooks:`` in ``mkdocs.yml``).

- **Includes.** Repository documents (the benchmark reports, the changelog, the contributing
  guide, ...) become site pages without being copied or moved: tests and links elsewhere point
  at them where they are. Their relative links are rewritten for the site: a link to another
  included document goes to its page, a link to any other repository file goes to the file on
  the repository host (``repo_url``), so the strict build checks every one of them.
- **Brand assets.** ``docs/assets/*`` is served as ``assets/*`` (logo and favicon).
- **CLI reference.** ``reference/cli.md`` is generated by ``docs/gen_cli.py`` on every build.
- **API pages.** Sphinx roles in docstrings (``:func:`~docrooter.load```) render as code.

The same link rewriting applies to the hand-written pages in ``docs/site/``, so a page can link
to ``../../../examples/quickstart.py`` exactly as it would on the repository host.
"""

from __future__ import annotations

import importlib.util
import posixpath
import re
from pathlib import Path
from typing import Any

from mkdocs.structure.files import File, Files

ROOT = Path(__file__).resolve().parents[1]
SITE_SOURCE = "docs/site"

# Site page -> repository file. Each is included verbatim, with its links rewritten.
INCLUDES: dict[str, str] = {
    "reference/taxonomy-formats.md": "docs/taxonomy-formats.md",
    "benchmarks/pdf.md": "docs/benchmarks-pdf.md",
    "benchmarks/heldout.md": "docs/benchmarks-heldout.md",
    "benchmarks/elements.md": "docs/benchmarks-elements.md",
    "benchmarks/public-datasets.md": "docs/benchmarks.md",
    "benchmarks/performance.md": "docs/performance.md",
    "about/changelog.md": "CHANGELOG.md",
    "about/contributing.md": "CONTRIBUTING.md",
    "about/security.md": "SECURITY.md",
    "about/code-of-conduct.md": "CODE_OF_CONDUCT.md",
}
ASSET_DIR = "docs/assets"
CLI_PAGE = "reference/cli.md"

_FENCE = re.compile(r"^\s*(```|~~~)")
_INLINE_LINK = re.compile(r"(\]\()(<?)([^)\s>]+)(>?)")
_REFERENCE_LINK = re.compile(r"^(\s{0,3}\[[^\]]+\]:\s+)(\S+)")
_HTML_LINK = re.compile(r"""((?:href|src)=")([^"]+)(")""")
_ROLE = re.compile(r":(?:func|meth|class|data|attr|mod|exc|obj):<code>~?([^<]*)</code>")

_repo_web: str = ""  # e.g. https://github.com/org/repo, from repo_url


def _sources() -> dict[str, str]:
    """Repository file -> site path, for every included page and asset."""
    mapping = {source: page for page, source in INCLUDES.items()}
    for path in sorted((ROOT / ASSET_DIR).iterdir()):
        if path.is_file():
            mapping[f"{ASSET_DIR}/{path.name}"] = f"assets/{path.name}"
    return mapping


def _gen_cli() -> Any:
    spec = importlib.util.spec_from_file_location("docrooter_gen_cli", ROOT / "docs/gen_cli.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def on_config(config: Any) -> Any:
    global _repo_web
    _repo_web = (config.repo_url or "").rstrip("/")
    return config


def on_files(files: Files, config: Any) -> Files:
    for page, source in INCLUDES.items():
        text = (ROOT / source).read_text(encoding="utf-8")
        files.append(File.generated(config, page, content=text))
    for source, target in _sources().items():
        if target.startswith("assets/"):
            files.append(File.generated(config, target, abs_src_path=str(ROOT / source)))
    files.append(File.generated(config, CLI_PAGE, content=_gen_cli().render()))
    return files


def on_page_markdown(markdown: str, page: Any, config: Any, files: Files) -> str:
    site_path = page.file.src_uri
    source = INCLUDES.get(site_path, f"{SITE_SOURCE}/{site_path}")
    return rewrite_links(markdown, source, site_path)


def on_page_content(html: str, page: Any, config: Any, files: Files) -> str:
    return _ROLE.sub(lambda m: f"<code>{m.group(1).rsplit('.', 1)[-1]}</code>", html)


def on_serve(server: Any, config: Any, builder: Any) -> Any:
    for source in INCLUDES.values():
        server.watch(str(ROOT / source))
    server.watch(str(ROOT / ASSET_DIR))
    server.watch(str(ROOT / "src/docrooter/cli.py"))
    return server


def rewrite_links(markdown: str, source: str, site_path: str) -> str:
    """Rewrite the relative links of ``markdown``, written at repository path ``source``, for
    the site page ``site_path``. Code blocks are left alone."""
    mapping = _sources()
    out: list[str] = []
    in_fence = False
    for line in markdown.split("\n"):
        if _FENCE.match(line):
            in_fence = not in_fence
        if not in_fence:

            def fix(match: re.Match[str], target_group: int) -> str:
                groups = list(match.groups())
                groups[target_group - 1] = _target(
                    groups[target_group - 1], source, site_path, mapping
                )
                return "".join(groups)

            line = _INLINE_LINK.sub(lambda m: fix(m, 3), line)
            line = _REFERENCE_LINK.sub(lambda m: fix(m, 2), line)
            line = _HTML_LINK.sub(lambda m: fix(m, 2), line)
        out.append(line)
    return "\n".join(out)


def _target(target: str, source: str, site_path: str, mapping: dict[str, str]) -> str:
    if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.IGNORECASE) or target.startswith(("#", "/")):
        return target  # external, mailto:, in-page anchor or site-absolute
    path, hash_, anchor = target.partition("#")
    if not path:
        return target
    repo_path = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if repo_path.startswith(".."):
        return target  # outside the repository: leave it for the link check to report
    here = posixpath.dirname(site_path) or "."
    suffix = f"{hash_}{anchor}"
    if repo_path in mapping:
        return posixpath.relpath(mapping[repo_path], here) + suffix
    if repo_path.startswith(f"{SITE_SOURCE}/"):
        return posixpath.relpath(repo_path[len(SITE_SOURCE) + 1 :], here) + suffix
    full = ROOT / repo_path
    if _repo_web and full.exists():
        kind = "tree" if full.is_dir() else "blob"
        return f"{_repo_web}/{kind}/main/{repo_path}{suffix}"
    return target  # unknown: the strict build reports it as a broken link
